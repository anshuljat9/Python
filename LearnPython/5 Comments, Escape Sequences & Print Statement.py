# This is a simple comment using hashtag (#)
# Everything after # in a line is ignored by Python

# Example of single line comment:
# This code prints Hello
print("Hello")  # This also prints Hello

# Example of multi-line comment using three single quotes:
'''
When we want to write many lines as comments,
we can use three single quotes at start and end.
Python will ignore everything between these quotes.
'''

# Example of multi-line comment using three double quotes:
"""
We can also use three double quotes
to write multiple lines as comments.
Both ways work the same!
"""

# Basic Escape Sequences in Python
# Escape sequences are special characters that do special things in text

''' \n makes text go to next line'''
print("First line\nSecond line")

''' \t adds a big space (tab)'''
print("Name:\tJohn")

''' \\ prints a single backslash'''
print("This shows one backslash: \\")

''' \' lets you use single quote(') in text'''
print('I\'m learning Python')

''' \" lets you use double quotes("") in text'''
print("He said \"Hello!\"")

''' Using multiple escape sequences together'''
print("Row 1\nRow 2\tColumn 2")
  
